"""Hand-off between the backend and the Steam-launched runner script.

The backend cannot start Moonlight itself: a process spawned by Decky is not
a Steam game, so gamescope would not focus its window and Steam Input would
not apply. Instead the frontend asks Steam to launch a hidden non-Steam
shortcut that points at ``moonlight-runner.sh``. The backend writes a one-shot
request file that tells the runner exactly what to execute; the runner writes
back a small result file when Moonlight exits.
"""

from __future__ import annotations

import json
import os
import time
from typing import Any, Dict, List, Optional

from .shellutil import quote

REQUEST_FILE = "launch-request.sh"
RESULT_FILE = "last-session.env"
LOG_FILE = "moonlight-last.log"
RUNNER_NAME = "moonlight-runner.sh"
REQUEST_MAX_AGE = 120  # seconds; mirrored in the runner script


def write_request(runtime_dir: str, argv: List[str], meta: Dict[str, Any]) -> str:
    """Atomically write a sourceable bash file with the Moonlight argv."""
    if not argv:
        raise ValueError("empty argv")
    lines = [
        "# Generated by Moondeck Apollo. One-shot: deleted by the runner.",
        f"ML_CREATED={int(time.time())}",
        "ML_ARGV=(" + " ".join(quote(a) for a in argv) + ")",
    ]
    for key, value in sorted(meta.items()):
        safe_key = "".join(c for c in key.upper() if c.isalnum() or c == "_")
        lines.append(f"ML_META_{safe_key}={quote(str(value))}")
    path = os.path.join(runtime_dir, REQUEST_FILE)
    tmp = path + ".tmp"
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    os.replace(tmp, path)
    return path


def clear_request(runtime_dir: str) -> None:
    try:
        os.remove(os.path.join(runtime_dir, REQUEST_FILE))
    except FileNotFoundError:
        pass


def read_result(runtime_dir: str) -> Optional[Dict[str, Any]]:
    """Parse the runner's KEY=VALUE result file plus the tail of Moonlight's log."""
    path = os.path.join(runtime_dir, RESULT_FILE)
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            text = f.read()
    except FileNotFoundError:
        return None
    result: Dict[str, Any] = {}
    for line in text.splitlines():
        if "=" in line:
            k, v = line.split("=", 1)
            result[k.strip().lower()] = v.strip()
    for key in ("exit_code", "started_at", "ended_at"):
        try:
            result[key] = int(result.get(key, ""))
        except ValueError:
            result[key] = None
    if result.get("started_at") and result.get("ended_at"):
        result["duration"] = result["ended_at"] - result["started_at"]
    log_tail = ""
    try:
        with open(os.path.join(runtime_dir, LOG_FILE), "rb") as f:
            f.seek(0, os.SEEK_END)
            size = f.tell()
            f.seek(max(0, size - 4000))
            log_tail = f.read().decode(errors="replace")
    except OSError:
        pass
    result["log_tail"] = log_tail
    return result


def install_runner(source: str, runtime_dir: str) -> str:
    """Copy the runner into the writable runtime dir and make it executable.

    Decky plugin zips do not reliably preserve the executable bit, and the
    runtime dir survives plugin updates, so the Steam shortcut keeps pointing
    at a stable path.
    """
    dest = os.path.join(runtime_dir, RUNNER_NAME)
    with open(source, "rb") as f:
        content = f.read()
    current = None
    if os.path.exists(dest):
        with open(dest, "rb") as f:
            current = f.read()
    if current != content:
        tmp = dest + ".tmp"
        with open(tmp, "wb") as f:
            f.write(content)
        os.replace(tmp, dest)
    os.chmod(dest, 0o755)
    return dest


def dump_json(obj: Any) -> str:
    return json.dumps(obj, sort_keys=True)
